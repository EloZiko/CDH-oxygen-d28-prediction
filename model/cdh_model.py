"""Prenatal prediction of oxygen dependency at day 28 in isolated left-sided CDH.

Final model of the article: CatBoost on four prenatal predictors, with missing
values left to the model (no imputation). Used by train.py, validate.py, the
tests and the scripts of analysis/.
"""
import json
import tempfile
from pathlib import Path

import pandas as pd
from catboost import CatBoostClassifier, Pool

FOLDER = Path(__file__).parent  # model/
ROOT = FOLDER.parent  # the repository
MODEL_PATH = FOLDER / "catboost_o2_d28.cbm"
WEB_MODEL_PATH = ROOT / "docs" / "model.js"

# The four predictors, in the order the model expects them (see data/README.md).
PREDICTORS = ["oe_lhr", "liver_herniation", "dvp", "oe_tflv"]
OUTCOME = "oxygen_d28"

# As in the article, a patient needs at least 2 of the 4 predictors.
MIN_PREDICTORS = 2

# Selected by randomized search with repeated cross-validation on the
# development cohort (article, Appendix E), then fixed.
HYPERPARAMETERS = {
    "iterations": 30,
    "depth": 2,
    "learning_rate": 0.014048580838867042,
    "l2_leaf_reg": 4.809862951501385,
    "auto_class_weights": "Balanced",  # both outcomes weigh the same in training
    "random_seed": 42,
}


def load_cohort(path, min_predictors=MIN_PREDICTORS):
    """Read a cohort CSV and keep the patients the model can be evaluated on:
    known outcome and at least `min_predictors` of the 4 predictors."""
    data = pd.read_csv(path)
    data = data.dropna(subset=[OUTCOME])
    data = data.dropna(subset=PREDICTORS, thresh=min_predictors)
    return data[PREDICTORS], data[OUTCOME].astype(int)


def train(X, y):
    """Fit the final model (allow_writing_files=False: no training logs on disk)."""
    model = CatBoostClassifier(**HYPERPARAMETERS, verbose=0, allow_writing_files=False)
    return model.fit(X[PREDICTORS], y)


def load_model(path=MODEL_PATH):
    return CatBoostClassifier().load_model(str(path))


def predict_high_risk(model, X):
    """True when the model predicts oxygen dependency at day 28.

    The tool reports this class only, not a probability: the predicted
    probabilities are poorly calibrated (article, Appendix G).
    """
    return model.predict(X[PREDICTORS]) == 1


def explain(model, X):
    """SHAP value of each predictor for each patient, on the log-odds scale.

    A positive value pushes the prediction towards oxygen dependency.
    """
    shap = model.get_feature_importance(Pool(X[PREDICTORS]), type="ShapValues")
    return pd.DataFrame(shap[:, :-1], columns=PREDICTORS, index=X.index)  # last column: average


def export_for_web(model, path=WEB_MODEL_PATH):
    """Write the trees of the model to a JavaScript file for the web tool.

    The page (docs/index.html) computes the prediction in the browser from this
    file, so the values entered by a clinician never leave their computer.
    """
    with tempfile.TemporaryDirectory() as folder:
        json_path = Path(folder) / "model.json"
        model.save_model(str(json_path), format="json")
        exported = json.loads(json_path.read_text())

    features = exported["features_info"]["float_features"]
    assert [feature["feature_id"] for feature in features] == PREDICTORS
    scale, bias = exported["scale_and_bias"]
    web_model = {
        "predictors": PREDICTORS,
        # The answer a missing value gives to every split question.
        "nanAsTrue": [feature["nan_value_treatment"] == "AsTrue" for feature in features],
        "scale": scale,
        "bias": bias[0],
        "trees": [
            {
                "splits": [[split["float_feature_index"], split["border"]] for split in tree["splits"]],
                "leafValues": tree["leaf_values"],
                "leafWeights": tree["leaf_weights"],
            }
            for tree in exported["oblivious_trees"]
        ],
    }
    Path(path).write_text(
        "// Generated by train.py: the trained model, used by predict.js.\n"
        f"const MODEL = {json.dumps(web_model)};\n"
    )
